"""Embed the unmodified FP32 inference tensors. Build-time Python standard library only."""
import hashlib
import json
from pathlib import Path
import struct

root=Path(__file__).resolve().parents[1]
source=root/'models/ambe2_hybrid.safetensors'
data=source.read_bytes()
size=struct.unpack_from('<Q',data)[0]
metadata=json.loads(data[8:8+size])
blob=bytearray();specs=[]
for name,tensor in sorted(metadata.items()):
    if name=='__metadata__' or name.endswith('.num_batches_tracked'): continue
    if tensor['dtype']!='F32': raise ValueError('Expected FP32 weights')
    start,end=tensor['data_offsets'];count=1
    for n in tensor['shape']: count*=n
    assert end-start==count*4
    while len(blob)%16: blob.append(0)
    specs.append('{"'+name+'",'+str(len(blob))+','+str(count)+'},')
    blob.extend(data[8+size+start:8+size+end])
build=root/'build/native';build.mkdir(parents=True,exist_ok=True)
(build/'model.bin').write_bytes(blob)
(build/'model_data.hpp').write_text('''// Generated by tools/embed-model.py. Do not edit.
#pragma once
#include <cstddef>
extern "C" const unsigned char t98_model_data[];
struct WeightSpec { const char* name; std::size_t offset, count; };
inline constexpr WeightSpec t98_weights[] = {
'''+ '\n'.join(specs)+'\n};\ninline constexpr const char* t98_model_sha256="'+hashlib.sha256(data).hexdigest()+'";\n')
(build/'model.S').write_text('.section .rdata,"dr"\n.balign 16\n.global t98_model_data\nt98_model_data:\n.incbin "build/native/model.bin"\n')
print('Embedded model:',len(blob),'bytes; SHA256',hashlib.sha256(data).hexdigest())
